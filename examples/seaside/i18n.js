export function localizeConfig(raw,language=lang){const c=structuredClone(raw);const text=(o,key)=>o.i18n?.[language]?.[key]??o[key];for(const key of ['name','tagline','memoryPrompt'])c[key]=text(c,key);for(const key of ['house','shop'])c[key].name=text(c[key],'name');for(const group of ['characters','menu','decor'])for(const item of c[group])item.name=text(item,'name');return c;}
export function initLanguageUI(){document.documentElement.lang=localeTag[lang];document.querySelectorAll('[data-i18n]').forEach(el=>el.textContent=t(el.dataset.i18n));document.querySelectorAll('[data-i18n-aria]').forEach(el=>el.setAttribute('aria-label',t(el.dataset.i18nAria)));document.querySelectorAll('[data-i18n-title]').forEach(el=>el.title=t(el.dataset.i18nTitle));const select=document.querySelector('#language');if(select){select.value=lang;select.onchange=()=>changeLanguage(select.value);}document.querySelectorAll('[data-guide-link]').forEach(a=>{const url=new URL(a.getAttribute('href'),location.href);url.searchParams.set('lang',lang);a.href=url;});}
